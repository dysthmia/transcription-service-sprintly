"""Шаблоны запросов к модели для создания учебных конспектов."""

from __future__ import annotations


def build_summary_prompt(source: str) -> str:
    """Формирует запрос для конспекта короткого материала."""
    return f"""Создай подробный учебный конспект материала.

Требования:
- пиши только на русском языке, даже если исходный материал на другом языке;
- верни Markdown с логичной иерархией заголовков;
- сохраняй важные определения, объяснения, примеры и выводы;
- сохраняй таблицы в Markdown, а различимые формулы — в LaTeX;
- не добавляй номера страниц, таймкоды, ссылки на источник или source locator;
- не выдумывай факты и не дополняй материал неподтверждённой информацией.

Исходный материал:
---
{source}
---"""


def build_chunk_summary_prompt(chunk: str, number: int, total: int) -> str:
    """Формирует запрос для подробного конспекта части большого материала."""
    return f"""Создай подробный промежуточный учебный конспект части {number} из {total}.

Пиши только на русском языке. Верни Markdown, сохрани важные определения,
объяснения, примеры, таблицы в Markdown и формулы в LaTeX. Не добавляй номера
страниц, таймкоды, source locator или неподтверждённые факты.

Часть исходного материала:
---
{chunk}
---"""


def build_merge_prompt(parts: list[str]) -> str:
    """Формирует запрос для объединения промежуточных конспектов по порядку."""
    numbered_parts = "\n\n".join(
        f"## Промежуточная часть {number}\n{part}"
        for number, part in enumerate(parts, start=1)
    )
    return f"""Объедини промежуточные конспекты в один подробный учебный конспект.

Пиши только на русском языке и верни только Markdown с логичной иерархией
заголовков. Сохрани порядок содержания, убери лишь явные повторы. Не теряй
важные определения, объяснения, примеры, Markdown-таблицы и формулы в LaTeX.
Не добавляй номера страниц, таймкоды, source locator или выдуманные факты.

Промежуточные конспекты:
---
{numbered_parts}
---"""
